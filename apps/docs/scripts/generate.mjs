// docs:generate — copies the published JSON Schemas, writes the generated
// reference pages from the core package and regenerates llm.txt / llms.txt at
// the repository root. Never edit the outputs by hand.
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import {
  coreSchemasDir,
  generatedDir,
  listSchemas,
  loadCore,
  publicSchemasDir,
  renderLlmTxt,
  renderLlmsTxt,
  repoRoot,
} from "./docs-lib.mjs"

const core = await loadCore()

// Outputs are formatted with the repository's Prettier when it is installed, so
// `pnpm format:check` stays green after regeneration.
const prettier = await import("prettier").then((m) => m.default ?? m).catch(() => null)
async function writeFormatted(file, content) {
  let output = content
  if (prettier) {
    const options = (await prettier.resolveConfig(file)) ?? {}
    output = await prettier.format(content, { ...options, filepath: file })
  }
  writeFileSync(file, output)
}

// 1. Schemas → public/schemas
mkdirSync(publicSchemasDir, { recursive: true })
const schemaFiles = readdirSync(coreSchemasDir).filter((name) => name.endsWith(".json"))
for (const name of schemaFiles)
  copyFileSync(join(coreSchemasDir, name), join(publicSchemasDir, name))
console.log(`schemas: copied ${schemaFiles.length} files to public/schemas`)

mkdirSync(generatedDir, { recursive: true })
const header = (title, description, source) =>
  `---\ntitle: ${title}\ndescription: ${description}\n---\n\n{/* Generated by apps/docs/scripts/generate.mjs from ${source}. Do not edit. */}\n\n`

// 2. Error codes
{
  const codes = Object.entries(core.ERROR_CODES)
  const rows = codes
    .map(
      ([code, { docs, hint }]) =>
        `| [\`${code}\`](#${code.toLowerCase()}) | [${docs}](/docs${docs}) | ${hint.replace(/\|/g, "\\|")} |`
    )
    .join("\n")
  const sections = codes
    .map(
      ([code, { docs, hint }]) =>
        `### ${code}\n\n${hint}\n\nDocumentation: [${docs}](/docs${docs}). Diagnostic URL: \`${core.DOCS_BASE_URL}${docs}\`.`
    )
    .join("\n\n")
  const body =
    header(
      "Error codes",
      "Every PlatformError code with its hint and the documentation page that explains the fix.",
      "internal/core/src/errors.ts (ERROR_CODES)"
    ) +
    `Every platform failure is a \`PlatformError\` carrying one of the ${codes.length} codes below, plus the owner (MFE, widget, instance), the source artefact, the available override, the hint and the documentation URL (\`${core.DOCS_BASE_URL}<path>\`). See [Troubleshooting](/docs/troubleshooting) for how to read one.\n\n` +
    `| Code | Docs | Hint |\n| --- | --- | --- |\n${rows}\n\n## Codes\n\n${sections}\n`
  await writeFormatted(join(generatedDir, "error-codes.mdx"), body)
  console.log(`error-codes.mdx: ${codes.length} codes`)
}

// 3. Capabilities
{
  const byCapability = new Map()
  for (const [api, capability] of Object.entries(core.CAPABILITY_BY_API)) {
    if (!byCapability.has(capability)) byCapability.set(capability, [])
    byCapability.get(capability).push(api)
  }
  const rows = core.CAPABILITY_IDS.map((id) => {
    const apis = byCapability.get(id) ?? []
    const implicit = core.IMPLICIT_CAPABILITIES.includes(id) ? "yes" : "no"
    return `| \`${id}\` | ${core.CAPABILITY_DESCRIPTIONS[id]} | ${implicit} | ${apis.map((api) => `\`${api}\``).join(", ") || "—"} |`
  }).join("\n")
  const body =
    header(
      "Capabilities",
      "Every capability a remote can request, what grants it and whether it is implicit.",
      "internal/core/src/capabilities.ts"
    ) +
    `Capabilities are requested by a remote (inferred by \`@platform/vite\` from the SDK APIs it uses, adjustable with \`capabilities: { add, remove }\` in \`mfe.config.ts\`) and approved by the host. The approved set is exposed through the platform context (\`usePlatform((p) => p.capabilities)\`, \`useCapability(id)\`); calling an API whose capability is not approved fails with \`CAPABILITY_UNAVAILABLE\`. Implicit capabilities are granted to every remote. See [Platform context](/docs/platform-context#capabilities). Schema: [\`/schemas/capabilities.json\`](/schemas/capabilities.json).\n\n` +
    `| Capability | Description | Implicit | Requested by |\n| --- | --- | --- | --- |\n${rows}\n`
  await writeFormatted(join(generatedDir, "capabilities.mdx"), body)
  console.log(`capabilities.mdx: ${core.CAPABILITY_IDS.length} capabilities`)
}

// 4. Schemas page
{
  const schemas = listSchemas()
  const rows = schemas
    .map(
      (schema) =>
        `| [\`${schema.file}\`](/schemas/${schema.file}) | ${schema.description} | \`${core.DOCS_BASE_URL.replace(/\/docs$/, "")}/schemas/${schema.file}\` |`
    )
    .join("\n")
  const body =
    header(
      "Schemas",
      "Machine-readable JSON Schemas (draft 2020-12) for every platform document, generated from the Zod schemas the platform validates with.",
      "internal/core/schemas/index.json"
    ) +
    `The schemas are generated by \`pnpm schemas:build\` in the core package and copied to this site by \`pnpm docs:generate\`. Reference them from a document with \`"$schema"\` for editor completion, or use them to validate generated artefacts.\n\n` +
    `| Schema | Describes | URL |\n| --- | --- | --- |\n${rows}\n\n` +
    `Related pages: [Manifest schema](/docs/reference/manifest-schema), [Runtime config schema](/docs/reference/runtime-config-schema), [Capabilities](/docs/reference/generated/capabilities), [Diagnostics](/docs/reference/diagnostics), [Dependency sharing](/docs/dependency-sharing).\n`
  await writeFormatted(join(generatedDir, "schemas.mdx"), body)
  console.log(`schemas.mdx: ${schemas.length} schemas`)
}

// 5. llm.txt and llms.txt at the repository root
writeFileSync(join(repoRoot, "llms.txt"), renderLlmsTxt())
writeFileSync(join(repoRoot, "llm.txt"), renderLlmTxt())
console.log("llms.txt and llm.txt written to the repository root")
